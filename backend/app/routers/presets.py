def _normalize_device(v) -> str:
    """设备角色归一化（后端无关语义值）。
    语义值 auto/discrete/integrated 原样保留；具体设备名或旧值映射为语义值：
      SYCL0/Vulkan1 → discrete（独显），SYCL1/Vulkan0 → integrated（核显），旧数字 0→discrete / 1→integrated。
    启动时由 instance_mgr 按当前后端动态解析成具体设备名（SYCL0/Vulkan1）。
    """
    if not v:
        return "auto"
    s = str(v).strip()
    low = s.lower()
    if low in ("auto", "discrete", "integrated"):
        return low
    if s.startswith("SYCL"):
        return "integrated" if s == "SYCL1" else "discrete"
    if s.startswith("Vulkan"):
        return "integrated" if s == "Vulkan0" else "discrete"
    if s.isdigit():
        return "discrete" if s == "0" else "integrated"
    return "auto"


def _find_mmproj(model_name: str) -> str:
    """在模型 gguf 同目录中查找 mmproj 文件（mmproj*.gguf）
    通过 services 表 model_path 定位模型文件所在目录，返回绝对路径或空串"""
    from pathlib import Path as _P
    base = _P(settings.model_dir)
    if not base.exists():
        return ""
    # 1) 通过 services 表拿到 model_path，找同目录
    search_dirs = []
    try:
        with get_conn() as conn:
            row = conn.execute("SELECT model_path FROM services WHERE name=?", (model_name,)).fetchone()
        if row and row["model_path"]:
            mp = row["model_path"].replace("/models/", "")
            p = base / mp
            search_dirs.append(p.parent if p.suffix else p)
    except Exception:
        pass
    # 2) 兜底：模型名是 gguf 文件名时，其目录 = base；否则扫描子目录
    if not search_dirs:
        if base.glob(f"{model_name}.gguf"):
            search_dirs.append(base)
        else:
            for d in base.iterdir():
                if d.is_dir() and d.name in model_name:
                    search_dirs.append(d)
    seen = set()
    for d in search_dirs:
        if not d.exists() or d in seen:
            continue
        seen.add(d)
        for p in sorted(d.glob("*mmproj*.gguf")):
            return str(p)
    return ""


def _write_config_ini() -> dict:
    """从 DB 全量生成 config.ini 并写入模型目录（幂等：先清空再重建）
    返回 {"ok": bool, "path": str, "content": str, "error": str?}
    """
    from pathlib import Path

    with get_conn() as conn:
        rows = conn.execute("SELECT * FROM model_presets ORDER BY model_name").fetchall()
        # 预设名 -> 模型文件路径（services 表），供 config.ini 的 model= 行
        path_rows = conn.execute("SELECT name, model_path FROM services").fetchall()
        path_by_name = {r["name"]: r["model_path"] for r in path_rows}

    lines = ["# llama-server router model presets", "# Auto-generated by llama-studio", ""]
    for r in rows:
        d = dict(r)
        lines.append(f"[{d['model_name']}]")
        # model= 必须显式绑定文件路径，llama.cpp 才会应用该段的 ctx/参数到对应模型
        mp = path_by_name.get(d["model_name"])
        if mp:
            lines.append(f"model = {mp}")
        lines.append(f"ctx-size = {d['ctx_size']}")
        lines.append(f"temp = {d['temp']}")
        lines.append(f"threads = {d['threads']}")
        lines.append(f"batch-size = {d['batch_size']}")
        lines.append(f"ubatch-size = {d['ubatch_size']}")
        lines.append(f"parallel = {d['parallel']}")
        lines.append(f"cache-type-k = {d['cache_type_k']}")
        lines.append(f"cache-type-v = {d['cache_type_v']}")
        if d["flash_attn"]:
            lines.append("flash-attn = on")
        if d["jinja"]:
            lines.append("jinja = on")
        if not d.get("mmap", 1):
            lines.append("no-mmap = on")
        # MoE 专家 offload CPU：0/空=全部专家层（cpu-moe = on）；N>0=仅前 N 层（n-cpu-moe = N）
        if d.get("cpu_moe"):
            _cmoe_n = d.get("cpu_moe_layers") or 0
            if _cmoe_n and _cmoe_n > 0:
                lines.append(f"n-cpu-moe = {_cmoe_n}")
            else:
                lines.append("cpu-moe = on")
        _ngl = d['n_gpu_layers']
        lines.append(f"n-gpu-layers = {('auto' if _ngl is not None and _ngl < 0 else _ngl)}")
        dev = _normalize_device(d.get("device"))
        # 语义值 → 具体设备名（后端无关；解析失败则写回语义值兜底）
        try:
            from app.instance_mgr import _resolve_device
            dev_resolved = _resolve_device(dev)
            if dev_resolved:
                dev = dev_resolved
        except Exception:
            pass
        lines.append(f"device = {dev}")
        # RoPE/YaRN 长上下文缩放（Qwen 社区建议 >32K 必须启用）
        rs = d.get("rope_scaling")
        if rs:
            lines.append(f"rope-scaling = {rs}")
            if d.get("rope_scale"):
                lines.append(f"rope-scale = {d['rope_scale']}")
            if d.get("yarn_orig_ctx"):
                lines.append(f"yarn-orig-ctx = {d['yarn_orig_ctx']}")
        # MTP 草稿 KV cache 量化（默认 f16 浪费显存，建议 q8_0）——仅非空才写，空则用默认
        if d.get("spec_draft_type_k"):
            lines.append(f"spec-draft-type-k = {d['spec_draft_type_k']}")
        if d.get("spec_draft_type_v"):
            lines.append(f"spec-draft-type-v = {d['spec_draft_type_v']}")
        # 思考（Reasoning）：--reasoning on/off/auto + --reasoning-budget N + --reasoning-effort
        reasoning = d.get("reasoning")
        if reasoning:
            lines.append(f"reasoning = {reasoning}")
            if d.get("reasoning_budget") is not None:
                lines.append(f"reasoning-budget = {d['reasoning_budget']}")
            if d.get("reasoning_effort"):
                lines.append(f"reasoning-effort = {d['reasoning_effort']}")
        # 自动检测 mmproj 并写入（多模态投影文件）
        mmproj = _find_mmproj(d["model_name"])
        if mmproj:
            lines.append(f"mmproj = {mmproj}")
        extra = json.loads(d["extra_args"] or "{}")
        # sampling 子对象展开为独立参数行（如 top-k = 40）
        sampling = extra.pop("sampling", None) if isinstance(extra, dict) else None
        if isinstance(sampling, dict):
            for k, v in sampling.items():
                if v is None or v == "":
                    continue
                lines.append(f"{k.replace('_', '-')} = {v}")
        for k, v in extra.items():
            lines.append(f"{k} = {v}")
        lines.append("")

    content = "\n".join(lines)
    config_path = Path(settings.model_dir) / "config.ini"
    try:
        config_path.parent.mkdir(parents=True, exist_ok=True)
        config_path.write_text(content)
        return {"ok": True, "path": str(config_path), "content": content}
    except Exception as e:
        return {"ok": False, "error": str(e), "content": content}


