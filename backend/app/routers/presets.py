@router.post("")
def create_preset(body: PresetCreate):
    """创建模型预设（单套，后端无关）"""
    with get_conn() as conn:
        dup = conn.execute(
            "SELECT id FROM model_presets WHERE model_name=?",
            (body.model_name,),
        ).fetchone()
        if dup:
            raise HTTPException(400, f"模型 {body.model_name} 的预设已存在")
        conn.execute(
            "INSERT INTO model_presets (model_name, ctx_size, temp, threads, batch_size, ubatch_size, "
            "parallel, cache_type_k, cache_type_v, flash_attn, jinja, n_gpu_layers, mmap, cpu_moe, cpu_moe_layers, mtp, mtp_model, mtp_n_max, spec_draft_type_k, spec_draft_type_v, device, rope_scaling, rope_scale, yarn_orig_ctx, reasoning, reasoning_budget, reasoning_effort, extra_args, created_at, updated_at) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (body.model_name, body.ctx_size, body.temp, body.threads, body.batch_size,
             body.ubatch_size, body.parallel, body.cache_type_k, body.cache_type_v,
             1 if body.flash_attn else 0, 1 if body.jinja else 0, body.n_gpu_layers,
             1 if body.mmap else 0, 1 if body.cpu_moe else 0, body.cpu_moe_layers or 0, 1 if body.mtp else 0, body.mtp_model or "",
             body.mtp_n_max or 3, body.spec_draft_type_k or "", body.spec_draft_type_v or "",
             _normalize_device(body.device), body.rope_scaling or "",
             body.rope_scale, body.yarn_orig_ctx, body.reasoning or "", body.reasoning_budget,
             body.reasoning_effort or "", json.dumps(body.extra_args), now(), now()),
        )
    # 同步生成 config.ini（router 重启后生效）
    _write_config_ini()
    return {"ok": True, "model_name": body.model_name, "backend": "universal"}


@router.put("/{pid}")
def update_preset(pid: int, body: PresetUpdate):
    """更新模型预设"""
    with get_conn() as conn:
        row = conn.execute("SELECT * FROM model_presets WHERE id=?", (pid,)).fetchone()
        if not row:
            raise HTTPException(404, "预设不存在")
        d = dict(row)
        updates = {}
        for field in ["ctx_size", "temp", "threads", "batch_size", "ubatch_size", "parallel",
                       "cache_type_k", "cache_type_v", "n_gpu_layers", "device"]:
            v = getattr(body, field, None)
            if v is not None:
                updates[field] = _normalize_device(v) if field == "device" else v
        if body.flash_attn is not None:
            updates["flash_attn"] = 1 if body.flash_attn else 0
        if body.jinja is not None:
            updates["jinja"] = 1 if body.jinja else 0
        if body.mmap is not None:
            updates["mmap"] = 1 if body.mmap else 0
        if body.cpu_moe is not None:
            updates["cpu_moe"] = 1 if body.cpu_moe else 0
        if body.cpu_moe_layers is not None:
            updates["cpu_moe_layers"] = body.cpu_moe_layers
        if body.mtp is not None:
            updates["mtp"] = 1 if body.mtp else 0
        if body.mtp_model is not None:
            updates["mtp_model"] = body.mtp_model
        if body.mtp_n_max is not None:
            updates["mtp_n_max"] = body.mtp_n_max
        # spec_draft_type_k/v：空串也是有效值（''=不传，用默认 f16），区分 None（不修改）与 ''（清空）
        if body.spec_draft_type_k is not None:
            updates["spec_draft_type_k"] = body.spec_draft_type_k
        if body.spec_draft_type_v is not None:
            updates["spec_draft_type_v"] = body.spec_draft_type_v
        # rope_scaling：空串也是有效值（''=关闭），需区分 None（不修改）与 ''（清空）
        if body.rope_scaling is not None:
            updates["rope_scaling"] = body.rope_scaling
            if body.rope_scaling == "":
                # 关闭缩放时联动清空 scale/orig（否则残留 0/旧值，面板显示像没关干净）
                updates["rope_scale"] = None
                updates["yarn_orig_ctx"] = None
            else:
                # 开启/切换缩放方法时，scale/orig 正常更新
                if body.rope_scale is not None:
                    updates["rope_scale"] = body.rope_scale
                if body.yarn_orig_ctx is not None:
                    updates["yarn_orig_ctx"] = body.yarn_orig_ctx
        else:
            if body.rope_scale is not None:
                updates["rope_scale"] = body.rope_scale
            if body.yarn_orig_ctx is not None:
                updates["yarn_orig_ctx"] = body.yarn_orig_ctx
        # reasoning：空串也是有效值（''=不配置），区分 None（不修改）与 ''（清空）
        if body.reasoning is not None:
            updates["reasoning"] = body.reasoning
            if body.reasoning == "":
                # 关闭思考时联动清空 budget 与 effort
                updates["reasoning_budget"] = None
                updates["reasoning_effort"] = ""
            else:
                if body.reasoning_budget is not None:
                    updates["reasoning_budget"] = body.reasoning_budget
                # 思考强度：空串也是有效值（''=用模板默认），区分 None（不修改）与 ''（清空）
                if body.reasoning_effort is not None:
                    updates["reasoning_effort"] = body.reasoning_effort
        else:
            if body.reasoning_budget is not None:
                updates["reasoning_budget"] = body.reasoning_budget
            if body.reasoning_effort is not None:
                updates["reasoning_effort"] = body.reasoning_effort
        if body.extra_args is not None:
            updates["extra_args"] = json.dumps(body.extra_args)

        if updates:
            sets = ", ".join(f"{k}=?" for k in updates)
            vals = list(updates.values()) + [now(), pid]
            conn.execute(f"UPDATE model_presets SET {sets}, updated_at=? WHERE id=?", vals)

    # 同步生成 config.ini（router 重启后生效）
    _write_config_ini()
    return {"ok": True}


