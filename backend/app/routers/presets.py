    @classmethod
    def _enum_string_normalize(cls, v):
        # 字符串枚举字段：可能收到布尔值（el-switch 误绑）或空串；'' 是有效关闭值不能归 None
        if v is None:
            return None
        if isinstance(v, bool):
            return "on" if v else ""
        if v == "":
            return ""
        return str(v)


