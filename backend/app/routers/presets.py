    threads: int = 8
    batch_size: int = 2048
    ubatch_size: int = 512
    parallel: int = 4
    cache_type_k: str = "q8_0"
    cache_type_v: str = "q8_0"
    flash_attn: bool = True
    jinja: bool = True
    n_gpu_layers: int = 99
    mmap: bool = True
    cpu_moe: bool = False
    cpu_moe_layers: int | None = None
    mtp: bool = False
